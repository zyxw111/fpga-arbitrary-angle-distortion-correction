"""Compile fixed inverse-affine/Brown settings; no third-party dependencies.

Positive angle rotates the displayed content counterclockwise in screen coords.
Forward affine is scale*R around output/source centers plus translation. Build
the inverse before Brown mapping: never forward-map into holes in the output.
"""
import argparse
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = "a00 a01 a02 a10 a11 a12 fx fy cx cy inv_fx inv_fy k1 k2 k3 p1 p2".split()

def parameters(c, host_check=True):
    for n in ('input_width', 'input_height', 'output_width', 'output_height'):
        if type(c[n]) is not int or not 8 <= c[n] <= 2048:
            raise ValueError(n + ': expected integer 8..2048')
    for w, h in [('input_width', 'input_height'), ('output_width', 'output_height')]:
        if c[w]*c[h] % 128:
            raise ValueError('Frame pixel count must be a multiple of 128')
    if c['input_width']*c['input_height']*2 > 0x800000:
        raise ValueError('Input overlaps OUTPUT_BASE (8 MiB)')
    if host_check and (c['output_width']>1920 or c['output_height']>1080):
        raise ValueError('Video output currently supports up to 1920x1080')
    for name, value in c.items():
        if isinstance(value, (int, float)) and not math.isfinite(value):
            raise ValueError('Nonfinite parameter: ' + name)
    if type(c['vs_active_high']) is not bool:
        raise ValueError('vs_active_high must be Boolean')
    if min(c['fx'], c['fy']) < 64 or not .125 <= c['scale'] <= 2:
        raise ValueError('Require fx/fy >=64 and scale .125..2')
    s = c['scale']; angle = math.radians(c['angle_degrees'])
    a = math.cos(angle)/s; b = -math.sin(angle)/s
    d = math.sin(angle)/s; e = math.cos(angle)/s
    ox = c['output_width']/2 + c['translate_x']
    oy = c['output_height']/2 + c['translate_y']
    result = dict(a00=a, a01=b, a02=c['cx']-a*ox-b*oy,
                  a10=d, a11=e, a12=c['cy']-d*ox-e*oy)
    result.update({n: c[n] for n in ('fx','fy','cx','cy','k1','k2','k3','p1','p2')})
    result.update(inv_fx=1/c['fx'], inv_fy=1/c['fy'])
    # Conservative numeric bound for the sequential Q16.16 implementation.
    corners = [(a*x+b*y+result['a02'], d*x+e*y+result['a12'])
               for x in (0,c['output_width']-1) for y in (0,c['output_height']-1)]
    nx = max(abs((x-c['cx'])/c['fx']) for x,y in corners)
    ny = max(abs((y-c['cy'])/c['fy']) for x,y in corners)
    r = nx*nx+ny*ny
    radial = 1+abs(c['k1'])*r+abs(c['k2'])*r*r+abs(c['k3'])*r*r*r
    bx = (nx*radial+2*abs(c['p1'])*nx*ny+abs(c['p2'])*(r+2*nx*nx))*c['fx']+abs(c['cx'])
    by = (ny*radial+abs(c['p1'])*(r+2*ny*ny)+2*abs(c['p2'])*nx*ny)*c['fy']+abs(c['cy'])
    if max(r,r*r,r*r*r,radial,bx,by) > 8000:
        raise ValueError('Mapping exceeds conservative Q16.16 working range')
    return result

def render(values):
    text='// Generated by tools/configure.py; edit config/warp.json and rebuild.\n'
    text+='module hdmi_config #(parameter RUNTIME=0)(input clk,input rst_n,input start,output ready,\n'
    text+=' input [543:0] runtime_config,\n'
    text+=' input [11:0] x,y,output valid,output signed [31:0] map_x,map_y);\n'
    text+=' hdmi_map mapper(.clk(clk),.rst_n(rst_n),.start(start),.ready(ready),\n'
    text+=' .x(x),.y(y),.valid(valid),.map_x(map_x),.map_y(map_y),\n'
    ports=[]
    words=[]
    for index,name in enumerate(ORDER):
        v=values[name]
        q=round(v*(1<<(30 if name.startswith('inv_') else 16)))
        if not -(1<<31)<=q<(1<<31): raise ValueError(name+' overflows signed32')
        words.append(f"32'h{q & 0xffffffff:08x}")
        ports.append(f" .{name}(RUNTIME ? $signed(runtime_config[{32*index}+:32]) : 32'sh{q & 0xffffffff:08x})")
    text+=',\n'.join(ports)+');\nendmodule\n'
    text+='module hdmi_defaults(output [543:0] defaults);\n assign defaults={'+','.join(reversed(words))+'};\nendmodule\n'
    return text

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('config',nargs='?',type=Path,default=ROOT/'config/warp.json')
    args=ap.parse_args(); c=json.loads(args.config.read_text(encoding='utf-8-sig'))
    values=parameters(c)
    (ROOT/'source/rtl/hdmi_config.v').write_text(render(values),encoding='ascii')
    top=ROOT/'source/rtl/hdmi_warp_top.v'
    text=top.read_text()
    line=('parameter integer WIDTH={output_width},HEIGHT={output_height},'
          'IN_WIDTH={input_width},IN_HEIGHT={input_height},VS_ACTIVE_HIGH='+str(int(c['vs_active_high'])))
    text,count=re.subn(r'parameter integer WIDTH=\d+,HEIGHT=\d+,IN_WIDTH=\d+,IN_HEIGHT=\d+,VS_ACTIVE_HIGH=\d+',line.format(**c),text)
    if count!=1: raise ValueError('Top geometry declaration was not found')
    top.write_text(text,encoding='ascii')
    print('PASS generated fixed warp parameters:', args.config)

if __name__=='__main__': main()
