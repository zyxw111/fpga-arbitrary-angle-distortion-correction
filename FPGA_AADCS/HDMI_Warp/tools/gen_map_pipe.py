"""Generate a one-coordinate/clock exact version of hdmi_map's arithmetic DAG.

Every intermediate remains signed 32 bits, with the original truncation at
each multiply. No polynomial approximation or new coordinate rounding.
Coefficients must remain stable until the valid pipeline drains (frame owner).
"""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ORDER='a00 a01 a02 a10 a11 a12 fx fy cx cy inv_fx inv_fy k1 k2 k3 p1 p2'.split()


def render():
    lines=['// Generated by tools/gen_map_pipe.py. Exact Q16.16 / Q2.30 Brown mapping.',
           'module hdmi_map_pipe(input clk,rst_n,in_valid,input [543:0] config_bank,',
           ' input [11:0] x,y,output out_valid,output signed [31:0] map_x,map_y);']
    levels={'xx':0,'yy':0};delays={};static=set(ORDER)|{'one'}
    lines += [" wire signed [31:0] xx={4'd0,x,16'd0},yy={4'd0,y,16'd0};",
              " wire signed [31:0] one=32'sd65536;"]
    for i,k in enumerate(ORDER):lines.append(f' wire signed [31:0] {k}=config_bank[{i*32}+:32];')
    regs=[];assignments=[]

    def at(k,level):
        if k in static:return k
        for stage in range(levels[k]+1,level+1):
            key=(k,stage)
            if key not in delays:
                previous=k if stage==levels[k]+1 else delays[k,stage-1]
                name=f'{k}_d{stage}'
                regs.append(name);assignments.append(f'  {name}<={previous};');delays[key]=name
        return k if level==levels[k] else delays[k,level]

    def add(name,inputs,expr):
        start=max((levels.get(k,0) for k in inputs),default=0)
        operands=[at(k,start) for k in inputs]
        levels[name]=start+1;regs.append(name)
        assignments.append(f'  {name}<='+expr.format(*operands)+';')

    def mul(name,a,b,shift=16):
        start=max(levels.get(a,0),levels.get(b,0));levels[name]=start+4
        aa,bb=at(a,start),at(b,start)
        lines.append(f' wire signed [63:0] {name}_product;')
        lines.append(f' warp_mul32_pipe mul_{name}(.clk(clk),.a({aa}),.b({bb}),.product({name}_product));')
        lines.append(f' wire signed [31:0] {name}={name}_product>>>{shift};')

    mul('ax0','xx','a00');mul('ax1','yy','a01')
    mul('ay0','xx','a10');mul('ay1','yy','a11')
    add('ax',['ax0','ax1','a02'],'{0}+{1}+{2}')
    add('ay',['ay0','ay1','a12'],'{0}+{1}+{2}')
    add('ncx',['ax','cx'],'{0}-{1}');add('ncy',['ay','cy'],'{0}-{1}')
    mul('nx','ncx','inv_fx',30);mul('ny','ncy','inv_fy',30)
    mul('x2','nx','nx');mul('y2','ny','ny');mul('xy','nx','ny')
    add('r2',['x2','y2'],'{0}+{1}')
    mul('r4','r2','r2');mul('r6','r4','r2')
    mul('kr2','k1','r2');mul('kr4','k2','r4');mul('kr6','k3','r6')
    add('scale',['one','kr2','kr4','kr6'],'{0}+{1}+{2}+{3}')
    add('twoxy',['xy'],'{0}<<<1')
    add('radiusx',['r2','x2'],'{0}+({1}<<<1)')
    add('radiusy',['r2','y2'],'{0}+({1}<<<1)')
    mul('tx0','p1','twoxy');mul('tx1','p2','radiusx')
    mul('ty0','p1','radiusy');mul('ty1','p2','twoxy')
    add('tx',['tx0','tx1'],'{0}+{1}');add('ty',['ty0','ty1'],'{0}+{1}')
    mul('dx0','nx','scale');mul('dy0','ny','scale')
    add('dx',['dx0','tx'],'{0}+{1}');add('dy',['dy0','ty'],'{0}+{1}')
    mul('px','dx','fx');mul('py','dy','fy')
    add('sx',['px','cx'],'{0}+{1}');add('sy',['py','cy'],'{0}+{1}')
    depth=max(levels['sx'],levels['sy'])
    sx,sy=at('sx',depth),at('sy',depth)
    lines += [f' localparam LATENCY={depth};',f' reg [LATENCY-1:0] valid_pipe;',
              f' assign map_x={sx}>>>4;assign map_y={sy}>>>4;',
              ' assign out_valid=valid_pipe[LATENCY-1];',
              ' always @(posedge clk or negedge rst_n)',
              " if(!rst_n)valid_pipe<=0;else valid_pipe<={valid_pipe[LATENCY-2:0],in_valid};"]
    # Declare before any instance port references (PDS/Icarus bind otherwise
    # as implicit wires, even when a later declaration has the same name).
    lines = lines[:3]+[f' reg signed [31:0] {k};' for k in regs]+lines[3:]
    lines += [' always @(posedge clk)begin']+assignments+[' end','endmodule','',
              '// Four stages, exactly the signed partial products used by hdmi_map.',
              'module warp_mul32_pipe(input clk,input signed [31:0] a,b,output reg signed [63:0] product);',
              ' reg signed [31:0] aa,bb,high_product;reg [31:0] low_product;',
              ' reg signed [32:0] high_low,low_high;reg signed [33:0] cross_term;',
              ' reg signed [63:0] base_product;',
              ' always @(posedge clk)begin',
              '  aa<=a;bb<=b;',
              '  low_product<=aa[15:0]*bb[15:0];',
              '  high_product<=$signed(aa[31:16])*$signed(bb[31:16]);',
              "  high_low<=$signed(aa[31:16])*$signed({1'b0,bb[15:0]});",
              "  low_high<=$signed({1'b0,aa[15:0]})*$signed(bb[31:16]);",
              '  cross_term<={high_low[32],high_low}+{low_high[32],low_high};',
              '  base_product<={high_product,low_product};',
              "  product<=base_product+{{14{cross_term[33]}},cross_term,16'd0};",
              ' end','endmodule']
    return '\n'.join(lines)+'\n'


if __name__=='__main__':
    (ROOT/'source/rtl/hdmi_map_pipe.v').write_text(render(),encoding='ascii')
